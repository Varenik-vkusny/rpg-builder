// Прибор С10: место в предложном падеже для полосы «Создано: Житель 1 в Рынке».
// Падеж не угадать (латиница, цифры, «в лесу», незнакомое окончание) — запасной вид
// «в месте «X»»: лучше честная формула, чем неверное окончание.
import 'package:flutter_test/flutter_test.dart';
import 'package:rpg_builder/map/ru_place.dart';

void main() {
  test('таблица имён: в Рынке, в Деревне, в Штольне, в Забое, в Копях…', () {
    const table = {
      'Рынок': 'в Рынке',
      'Деревня': 'в Деревне',
      'Забой': 'в Забое',
      'Копи': 'в Копях',
      'Бараки': 'в Бараках',
      'Лебёдка': 'в Лебёдке',
      'Новое место': 'в Новом месте',
      'Место 1': 'в Месте 1', // номер в конце не склоняется
      'Штольня': 'в Штольне',
      'Старая шахта': 'в Старой шахте',
      'Верхний ярус': 'в Верхнем ярусе',
      'Великий зал': 'в Великом зале',
      'Тёмные штреки': 'в Тёмных штреках',
      'Пепельные копи': 'в Пепельных копях',
      'Подземелье': 'в Подземелье',
      'Склад': 'в Складе',
      'Колодец': 'в Колодце',
      'Галерея': 'в Галерее',
      'Станция': 'в Станции',
      'Озеро': 'в Озере',
      'Шахты': 'в Шахтах',
      'Большой рудник': 'в Большом руднике',
    };
    for (final e in table.entries) {
      expect(inPlace(e.key), e.value, reason: e.key);
    }
  });

  test('падеж не угадать — «в месте «X»»', () {
    for (final n in [
      'Mine Entrance', // латиница
      'Тёмный лес', // «в лесу»
      'Порт', // «в порту»
      'Пещера Эха', // «Пещера» — существительное не в конце
      'Горячая', // ударение
      'Степь', // мягкий знак
      'Приток', // -ок: не рынок
      'Метро',
      '«Кабак»',
      '',
    ]) {
      final p = n.isEmpty ? null : prepositional(n);
      expect(p, isNull, reason: n);
    }
    expect(inPlace('Штольня №3'), 'в Штольне №3');
    expect(inPlace('Шахта 2'), 'в Шахте 2');
    expect(inPlace('№3'), 'в месте «№3»');
    expect(inPlace('Тёмный лес'), 'в месте «Тёмный лес»');
  });
}
