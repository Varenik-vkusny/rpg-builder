#!/usr/bin/env bash
# КАРТА ПРОЕКТА, КОТОРАЯ НЕ УМЕЕТ ВРАТЬ.
# Читает FEATURES.md, запускает у каждой строки её команду проверки
# и сам расставляет галочки. Статус тут не пишется руками — он вычисляется.
#
# Формат строки:  - [ ] Человеческое название | команда проверки
cd "$(dirname "$0")/.." || exit 1
F="FEATURES.md"
[ -f "$F" ] || { echo "Нет FEATURES.md — создай его, по строке на сценарий."; exit 1; }

# Защита: не мерить во время операции.
# Если в папке есть живая сессия — пересчёт даст ложную картину недостроенного кода.
# Живой считается сессия, шевелившаяся за последние 12 часов.
# Наличие файла — не доказательство жизни: жёстко убитая сессия оставляет отметки.
ALIVE=$(find .claude/sessions -type f -mmin -720 2>/dev/null | head -1)
if [ -n "$ALIVE" ] && [ "$1" != "--force" ]; then
  echo "ОТКАЗ: в проекте есть незавершённая сессия."
  echo "Пересчёт сейчас покажет недостроенный код как поломку."
  echo "Дождись конца сессии или запусти с --force, если точно знаешь, что делаешь."
  exit 1
fi

# ВНИМАНИЕ: переменную нельзя звать TMP. На Windows TMP — это переменная
# окружения, по которой MSBuild и другие сборщики ищут папку под временные
# файлы. Присвоив ей путь к ФАЙЛУ, мы роняем любой dotnet/msbuild внутри
# цикла, и строки красятся в красный по причине, не связанной с продуктом.
REWRITE="$(mktemp)"; OK=0; BAD=0; RUNS=0
CACHE="$(mktemp -d)"; trap 'rm -rf "$CACHE"' EXIT
while IFS= read -r line || [ -n "$line" ]; do
  if [[ "$line" =~ ^-[[:space:]]\[[[:space:]x]\][[:space:]](.+)\|(.+)$ ]]; then
    name="${BASH_REMATCH[1]}"; cmd="${BASH_REMATCH[2]}"
    name="$(echo "$name" | sed -e 's/[[:space:]]*$//')"
    cmd="$(echo "$cmd" | sed -e 's/^[[:space:]]*//')"
    # Одну и ту же команду гоняем ОДИН раз за прогон: десятки строк реестра
    # ссылаются на один прогон, и без этого пересчёт занимает час вместо минуты.
    key=$(printf '%s' "$cmd" | md5sum 2>/dev/null | cut -c1-32)
    [ -z "$key" ] && key=$(printf '%s' "$cmd" | cksum | tr -d ' /')
    if [ -f "$CACHE/$key" ]; then
      res=$(cat "$CACHE/$key")
    else
      if eval "$cmd" >/dev/null 2>&1; then res=0; else res=1; fi
      printf '%s' "$res" > "$CACHE/$key"; RUNS=$((RUNS+1))
    fi
    if [ "$res" -eq 0 ]; then
      printf -- '- [x] %s | %s\n' "$name" "$cmd" >> "$REWRITE"; OK=$((OK+1))
      printf '  ЗЕЛЁНО   %s\n' "$name"
    else
      printf -- '- [ ] %s | %s\n' "$name" "$cmd" >> "$REWRITE"; BAD=$((BAD+1))
      printf '  КРАСНО   %s\n' "$name"
    fi
  else
    printf '%s\n' "$line" >> "$REWRITE"
  fi
done < "$F"
mv "$REWRITE" "$F"

echo ""
if [ "$((OK+BAD))" -eq 0 ]; then
  echo "КРАСНО: НИ ОДНОЙ ИЗМЕРИМОЙ СТРОКИ."
  echo "Строки без команды после | — это намерения, а не приборы."
  echo "Формат измеримой строки:  - [ ] Что видит игрок | команда проверки"
  exit 1
fi
echo "ИТОГО: готово $OK из $((OK+BAD)).  Не готово: $BAD.  Прогонов: $RUNS"
[ "$BAD" -gt 0 ] && echo "Красные строки — это и есть честный ответ на вопрос «на каком мы этапе»."
exit 0
