// Все тексты справки — здесь и только здесь: по ключу поля и по ключу экрана.
// Поле: одна фраза «что это и зачем» + пример из «Пепельных копей», вместе не длиннее
// 120 знаков. Экран: до трёх строк по одной фразе. Правила стережёт test/help_texts_test.dart.

/// Справка поля формы.
class FieldHelp {
  const FieldHelp(this.title, this.what, this.example);

  /// Название поля — заголовок шторки.
  final String title;

  /// Одна фраза: что это и зачем.
  final String what;
  final String example;

  /// Текст целиком, как его считает предел длины.
  String get text => '$what Пример: $example';
}

/// Справка экрана: что здесь делают и что значат значки и цвета.
class ScreenHelp {
  const ScreenHelp(this.title, this.lines);
  final String title;
  final List<String> lines;
}

